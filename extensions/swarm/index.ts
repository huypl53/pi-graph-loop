async function captureGitCommit(pi: ExtensionAPI): Promise<{ available: boolean; baseCommit?: string; headCommit?: string }> {
	try {
		const r = await pi.exec("git", ["rev-parse", "HEAD"], { timeout: 5000 });
		if (r.code !== 0) return { available: false };
		const head = (r.stdout || "").trim();
		if (!head) return { available: false };
		// A single snapshot is intentionally NOT treated as proof of a change. A code/config-changing
		// run still needs a .patch/.diff ref unless callers later provide distinct base/head commits.
		return { available: true, baseCommit: head, headCommit: head };
	} catch {
		return { available: false };
	}
}

async function resolveEvidencePath(cwd: string, ref: string): Promise<string> {
	const [base, target] = await Promise.all([realpath(cwd), realpath(join(cwd, ref))]);
	if (target !== base && !target.startsWith(`${base}${sep}`)) throw new Error(`evidence ref resolves outside project cwd: ${ref}`);
	return target;
}

async function captureEvidenceDigests(cwd: string, refs: string[]): Promise<EvidenceDigest[]> {
	const out: EvidenceDigest[] = [];
	for (const ref of refs) {
		if (!isSafeRelativePath(ref)) continue;
		try {
			const data = await readFile(await resolveEvidencePath(cwd, ref));
			out.push({ ref, sha256: createHash("sha256").update(data).digest("hex"), size: data.byteLength });
		} catch { /* existence/boundary is enforced by the promotion gate, not run recording */ }
	}
	return out;
}

async function readJsonlRecords<T = any>(file: string): Promise<T[]> {
	let raw: string;
	try { raw = await readFile(file, "utf8"); } catch { return []; }
	const out: T[] = [];
	for (const line of raw.split("\n")) {
		const t = line.trim();
		if (!t) continue;
		try { out.push(JSON.parse(t) as T); } catch { /* malformed records are ignored by legacy readers */ }
	}
	return out;
}

// Append-only JSONL with status transitions: readers keep only the latest line per id field.
async function readJsonlLatestById<T extends Record<string, any>>(file: string, idField: string): Promise<T[]> {
	const all = await readJsonlRecords<T>(file);
	const latest = new Map<string, T>();
	for (const rec of all) {
		const id = rec?.[idField];
		if (typeof id === "string") latest.set(id, rec);
	}
	return Array.from(latest.values());
}

async function checkEvidenceRefs(cwd: string, refs: string[]): Promise<{ ok: boolean; reasons: string[]; checked: { ref: string; exists: boolean; readable: boolean }[] }> {
	const reasons: string[] = [];
	const checked: { ref: string; exists: boolean; readable: boolean }[] = [];
	for (const ref of refs) {
		if (!isSafeRelativePath(ref)) {
			reasons.push(`evidence ref is unsafe (must be relative, no ..): ${ref}`);
			checked.push({ ref, exists: false, readable: false });
			continue;
		}
		const lexical = join(cwd, ref);
		let exists = false;
		let readable = false;
		try {
			const abs = await resolveEvidencePath(cwd, ref);
			await readFile(abs, "utf8");
			exists = true;
			readable = true;
		} catch (err) {
			exists = existsSync(lexical);
			if (exists && String((err as Error)?.message || err).includes("outside project cwd")) reasons.push(`evidence ref resolves outside project cwd: ${ref}`);
		}
		checked.push({ ref, exists, readable });
		if (!exists) reasons.push(`evidence ref does not exist: ${ref}`);
		else if (!readable && !reasons.some((r) => r === `evidence ref resolves outside project cwd: ${ref}`)) reasons.push(`evidence ref exists but is not readable: ${ref}`);
	}
	return { ok: reasons.length === 0, reasons, checked };
}

function evidenceRequirementMatches(required: string, refs: string[]): boolean {
	const normalized = required.replace(/^\.\//, "");
	return refs.some((ref) => {
		const candidate = ref.replace(/^\.\//, "");
		if (candidate === normalized) return true;
		return !normalized.includes("/") && candidate.split("/").pop() === normalized;
	});
}

function metricValueMatchesContract(value: unknown, contract: MetricContract): boolean {
	if (contract.primaryMetric.valueType === "number") return typeof value === "number" && Number.isFinite(value);
	if (contract.primaryMetric.valueType === "boolean") return typeof value === "boolean";
	if (contract.primaryMetric.valueType === "string") return typeof value === "string";
	return false;
}

export function validateRunAgainstContract(run: RunRecord | undefined, contract: MetricContract | undefined): string[] {
	const reasons: string[] = [];
	if (!run) return ["run record does not exist"];
	if (!contract) return ["metric contract does not exist"];
	if (run.status !== "done") reasons.push(`run status is '${run.status || "(none)"}' (must be done)`);
	const verdict = (run.verdict || "").toLowerCase();
	if (verdict !== "pass" && verdict !== "approved") reasons.push(`run verdict is '${run.verdict || "(none)"}' (must be pass or approved)`);
	if (run.metricContractId !== contract.id) reasons.push(`run metricContractId is '${run.metricContractId || "(none)"}' (must be '${contract.id}')`);
	const contractVersion = contract.version || 1;
	if ((run.metricContractVersion || 0) !== contractVersion) reasons.push(`run metric contract version is '${run.metricContractVersion || "(none)"}' (current is ${contractVersion})`);
	const value = run.metrics?.[contract.primaryMetric.id];
	if (!metricValueMatchesContract(value, contract)) reasons.push(`primary metric '${contract.primaryMetric.id}' is missing or not a valid ${contract.primaryMetric.valueType}`);
	return reasons;
}

async function verifyEvidenceDigests(cwd: string, refs: string[], digests: EvidenceDigest[] | undefined): Promise<string[]> {
	const reasons: string[] = [];
	const byRef = new Map((digests || []).map((d) => [d.ref, d] as const));
	for (const ref of refs) {
		const recorded = byRef.get(ref);
		if (!recorded) { reasons.push(`evidence ref has no recorded digest: ${ref}`); continue; }
		try {
			const data = await readFile(await resolveEvidencePath(cwd, ref));
			const current = createHash("sha256").update(data).digest("hex");
			if (current !== recorded.sha256 || data.byteLength !== recorded.size) reasons.push(`evidence ref changed after run recording: ${ref}`);
		} catch { /* checkEvidenceRefs reports missing/unreadable */ }
	}
	return reasons;
}

// Evidence-backed memory gate. It validates terminal run quality, metric-contract/version binding,
// required evidence, immutable evidence digests, and reconstructability for code/config changes.
async function evaluateMemoryGate(opts: { cwd: string; run?: RunRecord; contract?: MetricContract; evidenceRefs: string[] }): Promise<{ accepted: boolean; reasons: string[] }> {
	const { run, contract, evidenceRefs, cwd } = opts;
	const reasons = validateRunAgainstContract(run, contract);
	if (!evidenceRefs || evidenceRefs.length === 0) {
		reasons.push("no evidenceRefs supplied");
	} else {
		const ev = await checkEvidenceRefs(cwd, evidenceRefs);
		if (!ev.ok) reasons.push(...ev.reasons);
		for (const required of contract?.evidenceRequired || []) {
			if (!evidenceRequirementMatches(required, evidenceRefs)) reasons.push(`required evidence is missing: ${required}`);
		}
		reasons.push(...await verifyEvidenceDigests(cwd, evidenceRefs, run?.evidenceDigests));
		const inputs = run?.inputs || {};
		const describesChange = Boolean(inputs.change || inputs.strategy || inputs.codeChanged || inputs.configChanged);
		const hasCommitRange = Boolean(run?.git?.baseCommit && run?.git?.headCommit && run.git.baseCommit !== run.git.headCommit);
		const hasDiff = evidenceRefs.some((r) => /\.(patch|diff)$/i.test(r));
		if (describesChange && !hasCommitRange && !hasDiff) reasons.push("code/config-changing run must include a .patch/.diff ref or distinct git base/head commits");
	}
	return { accepted: reasons.length === 0, reasons };
}

