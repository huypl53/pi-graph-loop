// Shared path to the project memory policy (a committed doc; agents read it relative to repo root).
// Declared in the memory-surface region; the identity region references this constant when appending
// the `## Memory protocol` link to generated agent identity. The dedicated policy file defines the
// read/propose/accept triggers, claim-quality rules, evidence requirements, and role permissions.
const MEMORY_POLICY_DOC = "docs/swarm-memory.md";

// Next-iteration retrieval bundle: best run summary + active memories that still pass the evidence
// gate. Ranking is deterministic: pinned first, then confidence, then recency. Scope matches kind+id.
// The bundle also surfaces `memoryPolicyRef` so the next-iteration agent is pointed at the policy.
async function buildIterationContext(p: Paths, session: IterationSession, runById: Map<string, RunRecord>, contract: MetricContract, best: IterationBest, memoryLimit = 10) {
	const metricId = contract.primaryMetric.id;
	const bestRun = best.bestRunId ? runById.get(best.bestRunId) : undefined;
	const baselineRun = session.baselineRunId ? runById.get(session.baselineRunId) : (session.iterations[0] ? runById.get(session.iterations[0].runId) : undefined);
	const lastEntry = session.iterations[session.iterations.length - 1];
	const lastRun = lastEntry ? runById.get(lastEntry.runId) : undefined;
	const memories = await latestMemories(p);
	const cwd = dirname(dirname(p.root));
	const scope = session.scope || { kind: "metric-contract", id: session.metricContractId };
	const candidates = memories
		.filter((m) => m.status === "active")
		.filter((m) => session.pinnedMemoryIds.includes(m.memoryId) || (m.scope?.kind === scope.kind && m.scope?.id === scope.id))
		.sort((a, b) => {
			const ap = session.pinnedMemoryIds.includes(a.memoryId) ? 1 : 0;
			const bp = session.pinnedMemoryIds.includes(b.memoryId) ? 1 : 0;
			if (ap !== bp) return bp - ap;
			if ((a.confidence || 0) !== (b.confidence || 0)) return (b.confidence || 0) - (a.confidence || 0);
			return (b.updatedAt || "").localeCompare(a.updatedAt || "");
		});
	const picked: MemoryRecord[] = [];
	const excludedMemories: { memoryId: string; reasons: string[] }[] = [];
	for (const m of candidates) {
		const run = runById.get(m.sourceRunId);
		const gate = await evaluateMemoryGate({ cwd, run, contract, evidenceRefs: m.evidenceRefs || [] });
		if (!gate.accepted) {
			excludedMemories.push({ memoryId: m.memoryId, reasons: gate.reasons });
			continue;
		}
		picked.push(m);
		if (picked.length >= memoryLimit) break;
	}
	const hint = `direction=${contract.primaryMetric.direction}; best=${best.bestRunId || "(none)"}${best.improvement !== undefined ? ` improvement=${best.improvement}` : ""}; meaningful=${best.meaningful}`;
	return {
		best: runSummary(bestRun, metricId),
		baseline: runSummary(baselineRun, metricId),
		last: runSummary(lastRun, metricId),
		memories: picked.map((m) => ({ memoryId: m.memoryId, claim: m.claim, sourceRunId: m.sourceRunId, evidenceRefs: m.evidenceRefs || [], scope: m.scope, confidence: m.confidence })),
		excludedMemories,
		memoryPolicyRef: MEMORY_POLICY_DOC,
		hint,
	};
}

// Explicit opt-in for the orchestrator/PM identity. Truthy PI_SWARM_IS_ORCHESTRATOR (1/true/yes)
// asserts "this session IS the human-driven orchestrator". A bare `pi` session opened in the project
// must NOT implicitly become the orchestrator: that would let it run the orchestrator mailbox pump
// (surfacing PM traffic to an unintended TUI), call ensureOrchestrator (refreshing the orchestrator
// pseudo-agent heartbeat and masking a dead/stalled PM), and default mailbox reads/sends to the
// orchestrator. The PM opts in explicitly; an anonymous session resolves to SWARM_GUEST_ID (inert).
function isOrchestratorSession() {
	const v = process.env.PI_SWARM_IS_ORCHESTRATOR;
	return Boolean(v) && !/^(0|false|no|)$/i.test(v.trim());
}

function currentAgentId() {
	// Explicit agent id always wins (spawned agents set PI_SWARM_AGENT_ID=<id>). Setting it to
	// "orchestrator" is an affirmative orchestrator claim, not a silent default.
	if (process.env.PI_SWARM_AGENT_ID) return process.env.PI_SWARM_AGENT_ID;
	// Explicit orchestrator opt-in (the human PM sets PI_SWARM_IS_ORCHESTRATOR=1).
	if (isOrchestratorSession()) return "orchestrator";
	// No identity and no explicit orchestrator claim: anonymous/inert swarm session.
	return SWARM_GUEST_ID;
}

function readSwarmSettings(cwd = process.cwd()): SwarmSettings {
	const file = join(cwd, CONFIG_DIR_NAME, "settings.json");
	if (!existsSync(file)) return {};
	try {
		const raw = JSON.parse(readFileSync(file, "utf8")) as Record<string, any>;
		const fromExtensions = raw?.extensions?.[EXT];
		const fromTopLevel = raw?.swarm;
		const cfg = (fromExtensions && typeof fromExtensions === "object" ? fromExtensions : undefined) ||
			(fromTopLevel && typeof fromTopLevel === "object" ? fromTopLevel : undefined);
		if (!cfg || typeof cfg !== "object") return {};
		return {
			defaultModel: typeof cfg.defaultModel === "string" && cfg.defaultModel.trim() ? cfg.defaultModel.trim() : undefined,
			defaultProvider: typeof cfg.defaultProvider === "string" && cfg.defaultProvider.trim() ? cfg.defaultProvider.trim() : undefined,
		};
	} catch {
		return {};
	}
}

